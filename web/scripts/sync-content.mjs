// Syncs the static site's catalog (../data, ../downloads) into the Next.js app
// and regenerates the Supabase seed. Run: npm run sync-content
import { cp, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readAndValidateCatalog } from './content-catalog.mjs';

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = path.resolve(webDir, '..');
const dataDir = path.join(repoDir, 'data');
const content = await readAndValidateCatalog(repoDir);
const files = ['goals', 'tools', 'paths', 'starter-packs', 'recommendations', 'starter-pack-checklists'];

await mkdir(path.join(webDir, 'content'), { recursive: true });
for (const name of files) {
  await cp(path.join(dataDir, `${name}.json`), path.join(webDir, 'content', `${name}.json`));
}
await cp(path.join(repoDir, 'downloads'), path.join(webDir, 'public', 'downloads'), { recursive: true });

const q = (value) => `'${String(value).replaceAll("'", "''")}'`;
const arr = (values) => `array[${values.map(q).join(', ')}]::text[]`;
const insert = (table, columns, rows, conflict) =>
  `insert into public.${table} (${columns.join(', ')}) values\n` +
  rows.map((row) => `  (${row.join(', ')})`).join(',\n') +
  `\non conflict (${conflict}) do update set ${columns
    .filter((c) => !conflict.split(', ').includes(c))
    .map((c) => `${c} = excluded.${c}`)
    .join(', ')};\n`;

const { goals, tools, paths, recommendations } = content;
const packs = content.starterPacks;
const recEntries = Object.entries(recommendations);

const sections = [
  '-- Generated by web/scripts/sync-content.mjs from data/*.json. Do not edit by hand.',
  'begin;',
  insert('goals', ['id', 'name', 'description', 'badge', 'position'],
    goals.map((g, i) => [q(g.id), q(g.name), q(g.description), q(g.badge), i]), 'id'),
  insert('tools', ['id', 'name', 'category', 'skill', 'description', 'badge', 'url', 'position'],
    tools.map((t, i) => [q(t.id), q(t.name), q(t.category), q(t.skill), q(t.description), q(t.badge), q(t.url), i]), 'id'),
  insert('starter_packs', ['id', 'title', 'description', 'level', 'file_path', 'position'],
    packs.map((p, i) => [q(p.id), q(p.title), q(p.description), q(p.level), q(p.file), i]), 'id'),
  insert('paths', ['id', 'title', 'level', 'description', 'badge', 'goal_id', 'steps', 'position'],
    paths.map((p, i) => [q(p.id), q(p.title), q(p.level), q(p.description), q(p.badge), q(p.goal), arr(p.steps), i]), 'id'),
  insert('recommendations', ['goal_id', 'title', 'summary', 'steps'],
    recEntries.map(([goalId, r]) => [q(goalId), q(r.title), q(r.summary), arr(r.steps)]), 'goal_id'),
  'delete from public.recommendation_tools;',
  insert('recommendation_tools', ['goal_id', 'tool_id', 'position'],
    recEntries.flatMap(([goalId, r]) => r.tools.map((toolId, i) => [q(goalId), q(toolId), i])), 'goal_id, tool_id'),
  'delete from public.recommendation_starters;',
  insert('recommendation_starters', ['goal_id', 'pack_id', 'position'],
    recEntries.flatMap(([goalId, r]) => r.starters.map((packId, i) => [q(goalId), q(packId), i])), 'goal_id, pack_id'),
  'commit;',
];

await writeFile(path.join(repoDir, 'supabase', 'seed.sql'), sections.join('\n') + '\n');
console.log(`Synced ${goals.length} goals, ${tools.length} tools, ${paths.length} paths, ${packs.length} packs, ${recEntries.length} recommendations.`);
